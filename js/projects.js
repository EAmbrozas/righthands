// Show 6 projects first, then load more
const projectGrid = document.querySelector("#projectGrid");
const filterButtons = document.querySelectorAll(".project-filter-btn");
const loadMoreProjectsBtn = document.querySelector("#loadMoreProjects");

let currentCategory = "all";
let visibleProjects = 6;
let currentFilteredProjects = [];

function getFilteredProjects(category = "all") {
  return category === "all"
    ? projects
    : projects.filter((project) => project.categories.includes(category));
}

function renderProjects(category = currentCategory) {
  projectGrid.innerHTML = "";

  currentFilteredProjects = getFilteredProjects(category);
  const projectsToShow = currentFilteredProjects.slice(0, visibleProjects);

  projectsToShow.forEach((project) => {
    const originalIndex = projects.indexOf(project);

    const card = document.createElement("article");

    card.className =
      "group bg-white rounded-3xl overflow-hidden border border-gray-200 shadow-sm hover:shadow-2xl hover:-translate-y-2 transition duration-500 cursor-pointer";

    card.innerHTML = `
      <div class="h-72 overflow-hidden">
        <img 
          src="${project.coverImage}" 
          alt="${project.alt}"
          loading="lazy"
          class="w-full h-full object-cover group-hover:scale-105 transition duration-700"
        >
      </div>

      <div class="p-8">
        <span class="text-sm font-semibold tracking-[0.18em] uppercase text-red-600">
          ${project.label}
        </span>

        <h3 class="text-2xl font-bold text-gray-900 mt-3 mb-4">
          ${project.title}
        </h3>

        <p class="text-gray-600 leading-relaxed mb-6">
          ${project.description}
        </p>

        <button
          class="view-project-btn inline-flex items-center text-red-600 font-semibold hover:text-red-700 transition"
          data-project-index="${originalIndex}">
          View Project Photos →
        </button>
      </div>
    `;

    projectGrid.appendChild(card);
  });

  if (visibleProjects >= currentFilteredProjects.length) {
    loadMoreProjectsBtn.classList.add("hidden");
  } else {
    loadMoreProjectsBtn.classList.remove("hidden");
  }
}

filterButtons.forEach((button) => {
  button.addEventListener("click", () => {
    currentCategory = button.dataset.category;
    visibleProjects = 6;

    filterButtons.forEach((btn) => btn.classList.remove("active-filter"));
    button.classList.add("active-filter");

    renderProjects(currentCategory);
  });
});

loadMoreProjectsBtn.addEventListener("click", () => {
  visibleProjects += 6;
  renderProjects(currentCategory);
});

// Project modal
const modal = document.querySelector("#projectModal");
const closeModalBtn = document.querySelector("#closeModal");

const modalMainImage = document.querySelector("#modalMainImage");
const modalThumbnails = document.querySelector("#modalThumbnails");

const prevImageBtn = document.querySelector("#prevImage");
const nextImageBtn = document.querySelector("#nextImage");

let activeProject = null;
let activeImageIndex = 0;

function openProjectModal(projectIndex) {
  activeProject = projects[projectIndex];
  activeImageIndex = 0;

  updateModalImage();

  modal.classList.remove("hidden");
  modal.classList.add("flex");
}

function closeProjectModal() {
  modal.classList.add("hidden");
  modal.classList.remove("flex");
}

function updateModalImage() {
  modalMainImage.src = activeProject.images[activeImageIndex];
  modalMainImage.alt = activeProject.alt;

  modalThumbnails.innerHTML = "";

  activeProject.images.forEach((image, index) => {
    const thumb = document.createElement("img");

    thumb.src = image;
    thumb.alt = `${activeProject.title} image ${index + 1}`;
    thumb.className =
      "w-24 h-24 object-cover rounded-xl cursor-pointer border-2 shrink-0";

    if (index === activeImageIndex) {
      thumb.classList.add("border-red-600");
    } else {
      thumb.classList.add("border-transparent");
    }

    thumb.addEventListener("click", () => {
      activeImageIndex = index;
      updateModalImage();
    });

    modalThumbnails.appendChild(thumb);
  });
}

projectGrid.addEventListener("click", (e) => {
  const btn = e.target.closest(".view-project-btn");

  if (!btn) return;

  openProjectModal(Number(btn.dataset.projectIndex));
});

nextImageBtn.addEventListener("click", () => {
  activeImageIndex++;

  if (activeImageIndex >= activeProject.images.length) {
    activeImageIndex = 0;
  }

  updateModalImage();
});

prevImageBtn.addEventListener("click", () => {
  activeImageIndex--;

  if (activeImageIndex < 0) {
    activeImageIndex = activeProject.images.length - 1;
  }

  updateModalImage();
});

closeModalBtn.addEventListener("click", closeProjectModal);

modal.addEventListener("click", (e) => {
  if (e.target === modal) {
    closeProjectModal();
  }
});

renderProjects();